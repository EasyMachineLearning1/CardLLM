# Корректирующее сообщение для повторной попытки, если модель вернула
# невалидный JSON или нарушила схему.
RETRY_INSTRUCTION = (
    "\n\nВАЖНО: твой предыдущий ответ не удалось разобрать (невалидный JSON или "
    "нарушена схема). Повтори ответ строго валидным JSON по схеме выше, "
    "без markdown-обёрток, пояснений и текста вокруг JSON."
)


def missing_input_hints(device: DeviceInput) -> list[str]:
    """Определить по входным данным, какие поля выглядят неполными."""
    hints: list[str] = []
    if not device.description.strip():
        hints.append("описание прибора (description) — данных нет")
    specs = device.specs.to_kv()
    if not specs:
        hints.append("характеристики (specs) — данных нет")
    elif len(specs) < 3:
        hints.append(
            "характеристики (specs) — предоставлено мало параметров, "
            "возможно, потребуется уточнение"
        )
    return hints


def build_prompt(request: GenerateRequest) -> str:
    """Собрать пользовательский промпт из данных прибора и схемы карточки."""
    device: DeviceInput = request.device
    specs_json = json.dumps(device.specs.to_kv(), ensure_ascii=False, indent=2)

    parts: list[str] = [
        f"Данные прибора:\n{device.model_dump_json(exclude={'specs'})}",
        f"Характеристики (JSON — единственный источник технических значений):\n{specs_json}",
    ]

    hints = missing_input_hints(device)
    if hints:
        parts.append(
            "Обрати внимание — во входных данных, вероятно, не хватает:\n- "
            + "\n- ".join(hints)
            + "\nУчти это при заполнении missing_fields, но карточку всё равно сформируй."
        )

    parts.append(_CARD_JSON_SCHEMA)
    return "\n\n".join(parts)
